"""Generate native palette constants from the vendored Catppuccin palette."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated():
    palettes = json.loads((ROOT / "shared/catppuccin.json").read_text())
    swift = "// Generated by scripts/generate-themes.py; Catppuccin, MIT (shared/CATPPUCCIN-LICENSE).\nimport Foundation\n\nstruct WorkbenchPalette: Equatable {\n    let name: String\n    let colors: [String: String]\n    let ansi: [String]\n    subscript(_ key: String) -> String { colors[key]! }\n"
    kotlin = "// Generated by scripts/generate-themes.py; Catppuccin, MIT (shared/CATPPUCCIN-LICENSE).\npackage com.cassette.workbench\n\ninternal data class WorkbenchPalette(val name: String, val colors: Map<String, String>, val ansi: List<String>) {\n    operator fun get(key: String): String = colors.getValue(key)\n    companion object {\n"
    for key, palette in palettes.items():
        swift += f'    static let {key} = WorkbenchPalette(name: "{palette["name"]}", colors: [\n'
        swift += ",\n".join(f'        "{k}": "{v}"' for k, v in palette["colors"].items())
        swift += "\n    ], ansi: " + json.dumps(palette["ansi"]) + ")\n"
        kotlin += f'        val {key} = WorkbenchPalette("{palette["name"]}", mapOf(\n'
        kotlin += ",\n".join(f'            "{k}" to "{v}"' for k, v in palette["colors"].items())
        kotlin += "\n        ), listOf(" + ", ".join(json.dumps(c) for c in palette["ansi"]) + "))\n"
    swift += "}\n"
    kotlin += "    }\n}\n"
    return {
        ROOT / "Sources/AgentWorkbench/WorkbenchPalette.swift": swift,
        ROOT / "android/app/src/main/java/com/cassette/workbench/WorkbenchPalette.kt": kotlin,
    }


if __name__ == "__main__":
    for path, content in generated().items():
        path.write_text(content)
